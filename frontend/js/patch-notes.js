let selectedPatchNoteVersion =
    "all";


// =========================================
// 버전 필터 출력
// =========================================

function renderPatchNoteVersionFilter() {

    patchNoteVersionFilterElement.innerHTML =
        "";


    const versionList = [
        "all",

        ...patchNoteData.map(
            (patchNote) =>
                patchNote.version
        ),
    ];


    versionList.forEach(
        (version) => {

            const buttonElement =
                document.createElement(
                    "button"
                );


            buttonElement.type =
                "button";


            buttonElement.classList.add(
                "patch-note-version-button"
            );


            buttonElement.textContent =
                version === "all"
                    ? "전체"
                    : version;


            if (
                selectedPatchNoteVersion
                === version
            ) {

                buttonElement.classList.add(
                    "active"
                );

            }


            buttonElement.addEventListener(
                "click",
                () => {

                    selectedPatchNoteVersion =
                        version;


                    renderPatchNoteVersionFilter();

                    renderPatchNotes();

                }
            );


            patchNoteVersionFilterElement
                .appendChild(
                    buttonElement
                );

        }
    );

}


// =========================================
// 패치노트 카드 출력
// =========================================

function renderPatchNotes() {

    patchNoteListElement.innerHTML =
        "";


    const filteredPatchNotes =
        selectedPatchNoteVersion
        === "all"
            ? patchNoteData
            : patchNoteData.filter(
                (patchNote) =>
                    patchNote.version
                    === selectedPatchNoteVersion
            );


    if (
        filteredPatchNotes.length
        === 0
    ) {

        patchNoteListElement.innerHTML = `
            <div class="patch-note-empty">
                등록된 패치노트가 없습니다.
            </div>
        `;

        return;

    }


    filteredPatchNotes.forEach(
        (patchNote) => {

            const cardElement =
                document.createElement(
                    "article"
                );


            cardElement.classList.add(
                "patch-note-card"
            );


            const summaryHtml =
                patchNote.summary
                    .map(
                        (summaryItem) => `
                            <li>
                                ${summaryItem}
                            </li>
                        `
                    )
                    .join("");


            const detailHtml =
                createPatchNoteDetailHtml(
                    patchNote.sections
                );


            cardElement.innerHTML = `
                <div
                    class="
                        patch-note-card-header
                    "
                >
                    <span
                        class="
                            patch-note-version
                        "
                    >
                        ${patchNote.version}
                    </span>

                    <time
                        class="
                            patch-note-date
                        "
                    >
                        ${patchNote.date}
                    </time>
                </div>


                <h2
                    class="
                        patch-note-title
                    "
                >
                    ${patchNote.title}
                </h2>


                <ul
                    class="
                        patch-note-summary
                    "
                >
                    ${summaryHtml}
                </ul>


                <div
                    class="
                        patch-note-detail
                    "
                    hidden
                >
                    ${detailHtml}
                </div>


                <button
                    type="button"
                    class="
                        patch-note-detail-button
                    "
                >
                    자세히 보기
                </button>
            `;


            const detailElement =
                cardElement.querySelector(
                    ".patch-note-detail"
                );


            const detailButtonElement =
                cardElement.querySelector(
                    ".patch-note-detail-button"
                );


            detailButtonElement.addEventListener(
                "click",
                () => {

                    const isOpen =
                        !detailElement.hidden;


                    detailElement.hidden =
                        isOpen;


                    detailButtonElement.textContent =
                        isOpen
                            ? "자세히 보기"
                            : "접기";

                }
            );


            patchNoteListElement.appendChild(
                cardElement
            );

        }
    );

}


// =========================================
// 패치 상세 내용 생성
// =========================================

function createPatchNoteDetailHtml(
    sections
) {

    return sections
        .map(
            (section) => {

                const itemHtml =
                    section.items
                        .map(
                            (item) => `
                                <li>
                                    ${item}
                                </li>
                            `
                        )
                        .join("");


                return `
                    <section
                        class="
                            patch-note-detail-section
                        "
                    >
                        <h3>
                            ${section.title}
                        </h3>

                        <ul>
                            ${itemHtml}
                        </ul>
                    </section>
                `;

            }
        )
        .join("");

}


// =========================================
// 초기화
// =========================================

function initializePatchNotes() {

    renderPatchNoteVersionFilter();

    renderPatchNotes();

}


initializePatchNotes();